package com.dsa.arrays.java;

public class ArrayTraversal {

    public static void main(String[] args) {

        int[] arr = {10, 30, 40};

        System.out.println("Array Traversal:");

        for (int i = 0; i < arr.length; i++) {
            System.out.println("Index: " + i + ", Value: " + arr[i]);
        }
    }
}